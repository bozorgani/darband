/* ----------------------------- Query helpers ----------------------------- */

export function getAllProducts(): Product[] {
  return products;
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getFeaturedProducts(limit = 6): Product[] {
  return products.filter((p) => p.featured).slice(0, limit);
}

export function getBestSellers(limit = 4): Product[] {
  return products.filter((p) => p.bestSeller).slice(0, limit);
}

export function getRelatedProducts(slug: string, limit = 4): Product[] {
  const product = getProductBySlug(slug);
  if (!product) return products.slice(0, limit);
  return products
    .filter((p) => p.slug !== slug)
    .map((p) => ({
      p,
      score:
        p.categories.filter((c) => product.categories.includes(c)).length * 2 +
        p.flavorNotes.filter((n) => product.flavorNotes.includes(n)).length,
    }))
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((x) => x.p);
}

export const allOrigins: string[] = Array.from(
  new Set(products.map((p) => p.origin?.country).filter(Boolean) as string[]),
);

